function renderIcons(options = {}) {
  const { root = document, ...createOptions } = options || {};
  return createIcons({
    ...createOptions,
    icons,
    root,
  });
}

window.lucide = Object.freeze({
  createIcons: renderIcons,
  icons,
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => renderIcons(), { once: true });
} else {
  renderIcons();
}
